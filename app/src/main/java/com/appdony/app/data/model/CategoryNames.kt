    private fun key(s: String): String = s.lowercase()
        .replace('ي', 'ی').replace('ك', 'ک')
        .replace("\u200c", " ").replace(Regex("\\s+"), " ").trim()

    /** اسم دسته‌ی خام وردپرس رو می‌گیره و اسم فارسی مرتب‌شده رو برمی‌گردونه */
    fun pretty(raw: String): String {
        val clean = raw.replace('ي', 'ی').replace('ك', 'ک').trim()
        MAP[key(clean)]?.let { return it }
        // اسم فارسی که از قبل درسته: فقط نیم‌فاصله‌ی «بازی‌های» رو درست می‌کنیم
        return clean.replace("بازی های", "بازی‌های").replace("بازی ها", "بازی‌ها")
    }
